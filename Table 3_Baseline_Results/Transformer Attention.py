def load_and_preprocess(vol_path, seg_path):
    try:
        vol_data = np.load(vol_path)
        seg_data = np.load(seg_path)
        if vol_data.size == 0 or seg_data.size == 0:
            raise ValueError("فایل خالی است")
        vol_resized = tf.image.resize(vol_data[..., np.newaxis], (128, 128)).numpy()
        seg_resized = tf.image.resize(seg_data[..., np.newaxis], (128, 128), method='nearest').numpy()
        vol_normalized = (vol_resized - vol_resized.min()) / (vol_resized.max() - vol_resized.min() + 1e-6)
        seg_resized = np.round(seg_resized).astype(np.uint8)
        seg_resized = np.clip(seg_resized[..., 0], 0, 2)
        return vol_normalized, seg_resized
    except Exception as e:
        print(f"خطا در بارگذاری {vol_path}, {seg_path}: {e}")
        return np.zeros((128, 128, 1)), np.zeros((128, 128))

def data_generator(pairs, batch_size=8):
    while True:
        np.random.shuffle(pairs)
        for i in range(0, len(pairs), batch_size):
            batch_pairs = pairs[i:i + batch_size]
            vol_batch = []
            seg_batch = []
            for vol_path, seg_path in batch_pairs:
                vol_norm, seg = load_and_preprocess(vol_path, seg_path)
                if np.any(seg > 2) or np.any(seg < 0):
                    print(f"برچسب نامعتبر در {seg_path}")
                    continue
                vol_batch.append(vol_norm)
                seg_batch.append(seg)
            if len(vol_batch) == 0:
                continue
            yield (np.array(vol_batch), np.array(seg_batch))

# تعریف معماری Transformer Attention U-Net
def patch_embedding(x, patch_size, embed_dim):
    """تبدیل تصویر به پچ‌ها و جاسازی آن‌ها"""
    patches = layers.Conv2D(embed_dim, kernel_size=patch_size, strides=patch_size, padding='valid')(x)
    patches = layers.Reshape((-1, embed_dim))(patches)  # تبدیل به (batch_size, num_patches, embed_dim)
    return patches

def transformer_block(x, num_heads, embed_dim, ff_dim, dropout_rate=0.1):
    """بلوک ترانسفورمر با Multi-Head Attention"""
    x_norm = layers.LayerNormalization(epsilon=1e-6)(x)
    x_attn = layers.MultiHeadAttention(num_heads=num_heads, key_dim=embed_dim // num_heads)(x_norm, x_norm)
    x = layers.Add()([x, x_attn])
    x = layers.Dropout(dropout_rate)(x)
    x_norm = layers.LayerNormalization(epsilon=1e-6)(x)
    x_ff = layers.Dense(ff_dim, activation='gelu')(x_norm)
    x_ff = layers.Dense(embed_dim)(x_ff)
    x = layers.Add()([x, x_ff])
    x = layers.Dropout(dropout_rate)(x)
    return x

def conv_block(x, filters, kernel_size=3):
    """بلوک کانولوشنی برای انکودر و دکودر"""
    x = layers.Conv2D(filters, kernel_size, padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)
    x = layers.Conv2D(filters, kernel_size, padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)
    return x

def transformer_attention_unet(input_shape=(128, 128, 1), num_classes=3, patch_size=16, embed_dim=256, num_heads=8, ff_dim=512):
    inputs = layers.Input(input_shape)

    # انکودر
    # سطح 1
    c1 = conv_block(inputs, 64)
    p1 = layers.MaxPooling2D((2, 2))(c1)  # 64x64x64

    # سطح 2
    c2 = conv_block(p1, 128)
    p2 = layers.MaxPooling2D((2, 2))(c2)  # 32x32x128

    # سطح 3
    c3 = conv_block(p2, 256)
    p3 = layers.MaxPooling2D((2, 2))(c3)  # 16x16x256

    # ترانسفورمر در سطح پایین
    patches = patch_embedding(p3, patch_size=patch_size, embed_dim=embed_dim)  # (batch_size, 1, embed_dim)
    x = transformer_block(patches, num_heads=num_heads, embed_dim=embed_dim, ff_dim=ff_dim)
    x = transformer_block(x, num_heads=num_heads, embed_dim=embed_dim, ff_dim=ff_dim)

    # بازسازی تصویر از پچ‌ها
    patch_grid = input_shape[0] // patch_size  # 128 // 16 = 8
    x = layers.Reshape((1, 1, embed_dim))(x)  # (batch_size, 1, 1, embed_dim)
    x = layers.Conv2DTranspose(512, (patch_size, patch_size), strides=(patch_size, patch_size), padding='valid')(x)  # 8x8x512
    bridge = layers.Conv2D(512, 1, padding='same')(x)  # 8x8x512

    # دکودر
    # سطح 3
    u3 = layers.Conv2DTranspose(256, (2, 2), strides=(2, 2), padding='same')(bridge)  # 16x16x256
    u3 = layers.Concatenate()([u3, c3])
    d3 = conv_block(u3, 256)

    # سطح 2
    u2 = layers.Conv2DTranspose(128, (2, 2), strides=(2, 2), padding='same')(d3)  # 32x32x128
    u2 = layers.Concatenate()([u2, c2])
    d2 = conv_block(u2, 128)

    # سطح 1
    u1 = layers.Conv2DTranspose(64, (2, 2), strides=(2, 2), padding='same')(d2)  # 64x64x64
    u1 = layers.Concatenate()([u1, c1])
    d1 = conv_block(u1, 64)

    # خروجی
    outputs = layers.Conv2D(num_classes, 1, activation='softmax')(d1)  # 128x128x3

    model = Model(inputs, outputs)
    return model

