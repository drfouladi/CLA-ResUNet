def post_process_predictions(pred_probs, tumor_threshold=0.35, liver_min_size=30, tumor_min_size=3):
    pred_labels = np.argmax(pred_probs, axis=-1).astype(np.uint8)
    tumor_probs = pred_probs[..., 2]
    tumor_pixels_before = np.sum(pred_labels == 2)
    pred_labels[(pred_labels == 2) & (tumor_probs < tumor_threshold)] = 0
    tumor_pixels_after_threshold = np.sum(pred_labels == 2)
    num_small_liver = num_small_tumor = 0
    for i in range(pred_labels.shape[0]):
        liver_mask = (pred_labels[i] == 1).astype(np.uint8)
        labeled_liver, num_features = measure.label(liver_mask, return_num=True)
        for label in range(1, num_features + 1):
            region_size = np.sum(labeled_liver == label)
            if region_size < liver_min_size:
                pred_labels[i][labeled_liver == label] = 0
                num_small_liver += 1
        tumor_mask = (pred_labels[i] == 2).astype(np.uint8)
        labeled_tumor, num_features = measure.label(tumor_mask, return_num=True)
        for label in range(1, num_features + 1):
            region_size = np.sum(labeled_tumor == label)
            if region_size < tumor_min_size:
                pred_labels[i][labeled_tumor == label] = 0
                num_small_tumor += 1
    print(f"تعداد پیکسل‌های تومور قبل از آستانه: {tumor_pixels_before}")
    print(f"تعداد پیکسل‌های تومور بعد از آستانه: {tumor_pixels_after_threshold}")
    print(f"تعداد نواحی کوچک حذف‌شده (کبد): {num_small_liver}")
    print(f"تعداد نواحی کوچک حذف‌شده (تومور): {num_small_tumor}")
    return pred_labels

