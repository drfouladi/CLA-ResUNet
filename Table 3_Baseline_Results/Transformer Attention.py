def calculate_metrics(model, val_gen, num_samples):
    liver_dice_sum = tumor_dice_sum = liver_iou_sum = tumor_iou_sum = 0
    liver_precision_sum = tumor_precision_sum = liver_recall_sum = tumor_recall_sum = 0
    liver_voe_sum = tumor_voe_sum = liver_rvd_sum = tumor_rvd_sum = 0
    liver_assd_sum = tumor_assd_sum = liver_msd_sum = tumor_msd_sum = 0
    liver_count = tumor_count = 0
    liver_vols_true = []
    liver_vols_pred = []
    tumor_vols_true = []
    tumor_vols_pred = []
    last_val_batch = None
    last_pred_labels = None

    def volumetric_overlap_error(y_true, y_pred):
        intersection = np.sum(y_true * y_pred)
        union = np.sum(y_true) + np.sum(y_pred) - intersection
        return 1 - (intersection / union) if union > 0 else 0

    def relative_volume_difference(y_true, y_pred):
        vol_true = np.sum(y_true)
        vol_pred = np.sum(y_pred)
        return abs(vol_pred - vol_true) / (vol_true + 1e-5) if vol_true > 0 else 0

    def average_symmetric_surface_distance(y_true, y_pred):
        true_border = np.array(np.where(np.abs(y_true - np.roll(y_true, 1, axis=0)) +
                                       np.abs(y_true - np.roll(y_true, 1, axis=1)))).T
        pred_border = np.array(np.where(np.abs(y_pred - np.roll(y_pred, 1, axis=0)) +
                                       np.abs(y_pred - np.roll(y_pred, 1, axis=1)))).T
        if true_border.size == 0 or pred_border.size == 0:
            return 0
        if len(true_border) > 1000:
            indices = np.random.choice(len(true_border), 1000, replace=False)
            true_border = true_border[indices]
        if len(pred_border) > 1000:
            indices = np.random.choice(len(pred_border), 1000, replace=False)
            pred_border = pred_border[indices]
        dist1 = np.mean(np.min(cdist(true_border, pred_border), axis=1))
        dist2 = np.mean(np.min(cdist(pred_border, true_border), axis=1))
        return (dist1 + dist2) / 2

    def maximum_surface_distance(y_true, y_pred):
        true_border = np.array(np.where(np.abs(y_true - np.roll(y_true, 1, axis=0)) +
                                       np.abs(y_true - np.roll(y_true, 1, axis=1)))).T
        pred_border = np.array(np.where(np.abs(y_pred - np.roll(y_pred, 1, axis=0)) +
                                       np.abs(y_pred - np.roll(y_pred, 1, axis=1)))).T
        if true_border.size == 0 or pred_border.size == 0:
            return 0
        if len(true_border) > 1000:
            indices = np.random.choice(len(true_border), 1000, replace=False)
            true_border = true_border[indices]
        if len(pred_border) > 1000:
            indices = np.random.choice(len(pred_border), 1000, replace=False)
            pred_border = pred_border[indices]
        dist1 = np.max(np.min(cdist(true_border, pred_border), axis=1))
        dist2 = np.max(np.min(cdist(pred_border, true_border), axis=1))
        return max(dist1, dist2)

    for i in range(num_samples):
        try:
            val_batch = next(val_gen)
            predictions = model.predict(val_batch[0], verbose=0)
            pred_probs = tf.nn.softmax(predictions, axis=-1).numpy()
            pred_labels = post_process_predictions(pred_probs)
            true_labels = val_batch[1]
            print(f"بچ {i+1} - توزیع پیش‌بینی‌ها: {np.bincount(pred_labels.flatten(), minlength=3)}")
            if i == 0:
                print("احتمال‌های اولیه (اولین نمونه):", pred_probs[0, 64, 64])
                print("برچسب پیش‌بینی‌شده:", pred_labels[0, 64, 64], "برچسب واقعی:", true_labels[0, 64, 64])
                print("تعداد پیکسل‌های واقعی کبد:", np.sum(true_labels[0] == 1))
                print("تعداد پیکسل‌های واقعی تومور:", np.sum(true_labels[0] == 2))
                print("توزیع واقعی:", np.bincount(true_labels.flatten().astype(int), minlength=3))
            for j in range(len(true_labels)):
                true_liver = (true_labels[j] == 1).astype(float)
                pred_liver = (pred_labels[j] == 1).astype(float)
                intersection_liver = np.sum(true_liver * pred_liver)
                denominator_liver = np.sum(true_liver) + np.sum(pred_liver)
                union_liver = np.sum(true_liver) + np.sum(pred_liver) - intersection_liver
                if denominator_liver > 0:
                    liver_dice = (2. * intersection_liver + 1e-5) / (denominator_liver + 1e-5)
                    liver_iou = (intersection_liver + 1e-5) / (union_liver + 1e-5)
                    liver_precision = np.sum(true_liver * pred_liver) / (np.sum(pred_liver) + 1e-5)
                    liver_recall = np.sum(true_liver * pred_liver) / (np.sum(true_liver) + 1e-5)
                    liver_voe = volumetric_overlap_error(true_liver, pred_liver)
                    liver_rvd = relative_volume_difference(true_liver, pred_liver)
                    liver_assd = average_symmetric_surface_distance(true_liver, pred_liver)
                    liver_msd = maximum_surface_distance(true_liver, pred_liver)
                    liver_dice_sum += liver_dice
                    liver_iou_sum += liver_iou
                    liver_precision_sum += liver_precision
                    liver_recall_sum += liver_recall
                    liver_voe_sum += liver_voe
                    liver_rvd_sum += liver_rvd
                    liver_assd_sum += liver_assd
                    liver_msd_sum += liver_msd
                    liver_vols_true.append(np.sum(true_liver))
                    liver_vols_pred.append(np.sum(pred_liver))
                    liver_count += 1
                true_tumor = (true_labels[j] == 2).astype(float)
                pred_tumor = (pred_labels[j] == 2).astype(float)
                intersection_tumor = np.sum(true_tumor * pred_tumor)
                denominator_tumor = np.sum(true_tumor) + np.sum(pred_tumor)
                union_tumor = np.sum(true_tumor) + np.sum(pred_tumor) - intersection_tumor
                if denominator_tumor > 0:
                    tumor_dice = (2. * intersection_tumor + 1e-5) / (denominator_tumor + 1e-5)
                    tumor_iou = (intersection_tumor + 1e-5) / (union_tumor + 1e-5)
                    tumor_precision = np.sum(true_tumor * pred_tumor) / (np.sum(pred_tumor) + 1e-5)
                    tumor_recall = np.sum(true_tumor * pred_tumor) / (np.sum(true_tumor) + 1e-5)
                    tumor_voe = volumetric_overlap_error(true_tumor, pred_tumor)
                    tumor_rvd = relative_volume_difference(true_tumor, pred_tumor)
                    tumor_assd = average_symmetric_surface_distance(true_tumor, pred_tumor)
                    tumor_msd = maximum_surface_distance(true_tumor, pred_tumor)
                    tumor_dice_sum += tumor_dice
                    tumor_iou_sum += tumor_iou
                    tumor_precision_sum += tumor_precision
                    tumor_recall_sum += tumor_recall
                    tumor_voe_sum += tumor_voe
                    tumor_rvd_sum += tumor_rvd
                    tumor_assd_sum += tumor_assd
                    tumor_msd_sum += tumor_msd
                    tumor_vols_true.append(np.sum(true_tumor))
                    tumor_vols_pred.append(np.sum(pred_tumor))
                    tumor_count += 1
            last_val_batch = val_batch
            last_pred_labels = pred_labels
        except Exception as e:
            print(f"خطا در بچ {i}: {e}")
            continue
    mean_dice_liver = liver_dice_sum / liver_count if liver_count > 0 else 0
    mean_dice_tumor = tumor_dice_sum / tumor_count if tumor_count > 0 else 0
    mean_iou_liver = liver_iou_sum / liver_count if liver_count > 0 else 0
    mean_iou_tumor = tumor_iou_sum / tumor_count if tumor_count > 0 else 0
    mean_precision_liver = liver_precision_sum / liver_count if liver_count > 0 else 0
    mean_precision_tumor = tumor_precision_sum / tumor_count if tumor_count > 0 else 0
    mean_recall_liver = liver_recall_sum / liver_count if liver_count > 0 else 0
    mean_recall_tumor = tumor_recall_sum / tumor_count if liver_count > 0 else 0
    mean_voe_liver = liver_voe_sum / liver_count if liver_count > 0 else 0
    mean_voe_tumor = tumor_voe_sum / tumor_count if tumor_count > 0 else 0
    mean_rvd_liver = liver_rvd_sum / liver_count if liver_count > 0 else 0
    mean_rvd_tumor = tumor_rvd_sum / tumor_count if tumor_count > 0 else 0
    mean_assd_liver = liver_assd_sum / liver_count if liver_count > 0 else 0
    mean_assd_tumor = tumor_assd_sum / tumor_count if tumor_count > 0 else 0
    mean_msd_liver = liver_msd_sum / liver_count if liver_count > 0 else 0
    mean_msd_tumor = tumor_msd_sum / tumor_count if tumor_count > 0 else 0
    icc_liver = r2_score(liver_vols_true, liver_vols_pred) if liver_count > 0 and len(liver_vols_true) > 1 and np.var(liver_vols_true) > 0 else 0
    icc_tumor = r2_score(tumor_vols_true, tumor_vols_pred) if tumor_count > 0 and len(tumor_vols_true) > 1 and np.var(tumor_vols_true) > 0 else 0
    print(f"تعداد نمونه‌های Liver: {liver_count}, Tumor: {tumor_count}")
    return (mean_dice_liver, mean_dice_tumor, mean_iou_liver, mean_iou_tumor,
            mean_precision_liver, mean_precision_tumor, mean_recall_liver, mean_recall_tumor,
            mean_voe_liver, mean_voe_tumor, mean_rvd_liver, mean_rvd_tumor,
            mean_assd_liver, mean_assd_tumor, mean_msd_liver, mean_msd_tumor,
            icc_liver, icc_tumor,
            last_val_batch, last_pred_labels)

