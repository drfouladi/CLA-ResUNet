def dice_avg(y_true, y_pred):
    dice_l = dice_liver(y_true, y_pred)
    dice_t = dice_tumor(y_true, y_pred)
    return (dice_l + dice_t) / 2

def tversky_loss(y_true, y_pred, alpha=0.6, beta=0.4):
    y_true_f = tf.one_hot(tf.cast(y_true, tf.int32), depth=3)
    y_pred_f = tf.nn.softmax(y_pred, axis=-1)
    numerator = tf.reduce_sum(y_true_f * y_pred_f, axis=[1, 2])
    denominator = numerator + alpha * tf.reduce_sum(y_true_f * (1 - y_pred_f), axis=[1, 2]) + \
                  beta * tf.reduce_sum((1 - y_true_f) * y_pred_f, axis=[1, 2])
    tversky = numerator / (denominator + 1e-5)
    return tf.where(denominator > 0, 1 - tf.reduce_mean(tversky), 0.0)

def focal_loss(gamma=2., alpha=0.25):
    def focal_loss_fixed(y_true, y_pred):
        y_true = tf.one_hot(tf.cast(y_true, tf.int32), depth=3)
        y_pred = tf.clip_by_value(y_pred, 1e-7, 1. - 1e-7)
        ce = -y_true * tf.math.log(y_pred)
        weight = y_true * tf.pow(1 - y_pred, gamma)
        fl = alpha * weight * ce
        return tf.reduce_mean(fl)
    return focal_loss_fixed

