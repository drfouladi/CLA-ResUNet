class LearningAutomata:
    def __init__(self, num_classes=3, initial_weights=None, alpha=0.18, beta=0.09, liver_priority=1.5, tumor_priority=4.0):
        self.num_classes = num_classes
        self.alpha = alpha
        self.beta = beta
        self.liver_priority = liver_priority
        self.tumor_priority = tumor_priority
        self.weights = np.array(initial_weights) if initial_weights is not None else np.ones(num_classes)
        self.probabilities = self.weights / np.sum(self.weights)
        self.history = []
        self.best_weights = self.weights.copy()
        self.best_metric = 0.0
        self.moving_avg_dice_liver = []
        self.moving_avg_dice_tumor = []
        self.window_size = 5
        self.tumor_boost = 1.0

    def select_action(self):
        if len(self.moving_avg_dice_tumor) >= self.window_size and np.mean(self.moving_avg_dice_tumor[-self.window_size:]) < 0.80:
            return 2
        elif len(self.moving_avg_dice_liver) >= self.window_size and np.mean(self.moving_avg_dice_liver[-self.window_size:]) < 0.90:
            return 1
        else:
            adjusted_probs = self.probabilities.copy()
            adjusted_probs[1] *= self.liver_priority
            adjusted_probs[2] *= self.tumor_priority * self.tumor_boost
            adjusted_probs /= np.sum(adjusted_probs)
            return np.random.choice(self.num_classes, p=adjusted_probs)

    def update_weights(self, selected_class, reward, metric, liver_metric, tumor_metric, precision_liver, epoch):
        self.moving_avg_dice_liver.append(liver_metric)
        self.moving_avg_dice_tumor.append(tumor_metric)

        if len(self.moving_avg_dice_tumor) >= self.window_size:
            avg_dice_tumor = np.mean(self.moving_avg_dice_tumor[-self.window_size:])
            if avg_dice_tumor < 0.80:
                self.tumor_boost = min(self.tumor_boost + 0.1, 3.0)
            else:
                self.tumor_boost = max(self.tumor_boost - 0.05, 1.0)

        combined_metric = 0.3 * liver_metric + 0.5 * tumor_metric + 0.2 * precision_liver

        if combined_metric > self.best_metric:
            self.best_metric = combined_metric
            self.best_weights = self.weights.copy()
            print(f"بهترین وزن‌ها به‌روزرسانی شدند: پس‌زمینه={self.best_weights[0]:.1f}, "
                  f"کبد={self.best_weights[1]:.1f}, تومور={self.best_weights[2]:.1f}, "
                  f"ضریب تقویت تومور={self.tumor_boost:.2f}")

        alpha = self.alpha * np.exp(-epoch / 50) + 0.01
        beta = self.beta * np.exp(-epoch / 50) + 0.005

        if reward > 0:
            self.weights[selected_class] += alpha * (10 - self.weights[selected_class])
            if selected_class == 2 and tumor_metric < 0.80:
                self.weights[2] += alpha * self.tumor_boost * 1.5
            if selected_class == 1 and liver_metric > 0.90:
                self.weights[0] = max(1.0, self.weights[0] - alpha * 0.3)
        else:
            self.weights[selected_class] = max(1.0, self.weights[selected_class] - beta * self.weights[selected_class])
            if selected_class != 2 and tumor_metric < 0.80:
                self.weights[2] += alpha * self.tumor_boost * 0.5
            if selected_class != 1 and liver_metric < 0.90:
                self.weights[1] += alpha * 0.3

        self.weights = np.clip(self.weights, 1.0, 10.0)
        self.probabilities = self.weights / np.sum(self.weights)
        self.history.append({
            'weights': self.weights.tolist(),
            'metric': float(metric),
            'liver_metric': float(liver_metric),
            'tumor_metric': float(tumor_metric),
            'precision_liver': float(precision_liver),
            'tumor_boost': float(self.tumor_boost)
        })

    def get_weights(self):
        return self.weights

    def get_best_weights(self):
        return self.best_weights

    def save_history(self, filepath):
        with open(filepath, 'w') as f:
            json.dump(self.history, f, indent=4)

# تعریف تابع loss با LA
def combined_loss_with_la(la):
    def loss(y_true, y_pred):
        current_weights = la.get_weights()
        adjusted_weights = np.clip(current_weights, 1.0, 8.0)
        adjusted_weights[2] *= la.tumor_boost
        ce_loss = tf.keras.losses.sparse_categorical_crossentropy(y_true, y_pred)
        weights = tf.cast(tf.gather(adjusted_weights, tf.cast(y_true, tf.int32)), tf.float32)
        weighted_ce = tf.reduce_mean(ce_loss * weights)
        focal = focal_loss(gamma=2., alpha=0.25)(y_true, y_pred)
        tversky = tversky_loss(y_true, y_pred, alpha=0.6, beta=0.4)
        return 0.25 * weighted_ce + 0.25 * focal + 0.5 * tversky
    return loss

